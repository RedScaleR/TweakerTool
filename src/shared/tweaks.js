// TweakerTool tweak catalog.
//
// Every tweak is a list of declarative operations. The main process turns
// them into PowerShell, snapshots the previous values before applying, and
// restores that snapshot (or the declared default) when a tweak is reverted.
//
//   reg  - registry value.  `revert: null` deletes the value on revert.
//   svc  - service start mode (auto | delayed-auto | demand | disabled).
//   task - scheduled task that is disabled when applied.
//   ps   - custom PowerShell with check / apply / revert scripts.
//
// Registry keys use short hive names (HKLM, HKCU, HKU).

const R = String.raw;

const dword = (key, name, value, revert = null) => ({ type: 'reg', key, name, kind: 'DWord', value, revert });
const str = (key, name, value, revert = null) => ({ type: 'reg', key, name, kind: 'String', value, revert });
const svc = (name, start, revert) => ({ type: 'svc', name, start, revert });
const task = (path, name) => ({ type: 'task', path, name });
const ps = (check, apply, revert) => ({ type: 'ps', check, apply, revert });

